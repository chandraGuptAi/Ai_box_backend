"""Typed numeric evidence and safe correction diagnostics for report narratives."""
from __future__ import annotations

import re
from datetime import date
from decimal import Decimal
from typing import Any

from app.errors import AIResponseError

_NUMBER = re.compile(r"(?<![\w.])[-+]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?(?![\w]|\.\d)")
_LIST_MARKER = re.compile(r"(?m)^\s*\d+[.)]\s+")
_DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")
_MONTH_NAMES = (
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
)
_MONTH_NUMBERS = {alias.lower(): number for number, name in enumerate(_MONTH_NAMES, 1)
                  for alias in (name, name[:3], *(["Sept"] if number == 9 else []))}
_MONTH_PATTERN = "(?:" + "|".join(sorted(_MONTH_NUMBERS, key=len, reverse=True)) + r")\.?"
_DATE_CLAIM = re.compile(
    r"\b(?:\d{4}-\d{2}-\d{2}|"
    rf"(?P<day_first>\d{{1,2}})(?:st|nd|rd|th)?\s+(?P<month_after>{_MONTH_PATTERN})\s+(?P<year_last>\d{{4}})|"
    rf"(?P<month_first>{_MONTH_PATTERN})\s+(?P<day_after>\d{{1,2}})(?:st|nd|rd|th)?(?:,\s*|\s+)(?P<year_after>\d{{4}}))\b",
    re.I,
)


def _normalized_date(match):
    """Parse only unambiguous ISO/English dates, independent of server locale."""
    try:
        if match["day_first"]:
            day, month, year = match["day_first"], match["month_after"], match["year_last"]
        elif match["month_first"]:
            day, month, year = match["day_after"], match["month_first"], match["year_after"]
        else:
            return date.fromisoformat(match.group()).isoformat()
        return date(int(year), _MONTH_NUMBERS[month.rstrip(".").lower()], int(day)).isoformat()
    except ValueError:
        return None


_STRUCTURE_FIELDS = {"id", "order", "type", "table_id", "severity", "priority"}
_TARGET = re.compile(r"\b(target|goal|aim|achieve|increase to|reduce to|raise to|reach|deadline)\b", re.I)
_IDENTIFIER = re.compile(r"\b(?:reference|identifier|order id|awb|tracking id)\s*[:#]?\s*(\d+)\b", re.I)
# Count nouns that make a number a count/coverage figure even inside a "financial" sentence.
_COUNT_NOUN = re.compile(r"\s*(?:of\s+[\d,]+\s+(?:orders?|shipments?|records?)|(?:cancelled|delivered|pending|in transit)\s+orders?|orders?|shipments?|records?|fields?|couriers?|labels?|groups?|rows?)\b", re.I)
_WORD = re.compile(r"[a-z]+", re.I)
# Counted noun right after the number, optionally preceded by up to two status words
# ("15 cancelled shipments", "64 orders"). Only letters, so "across 64 orders" never qualifies.
_COUNT_AFTER = re.compile(
    r"\s*(?:(?:cancelled|canceled|delivered|undelivered|rto|cod|prepaid|topay|pending|valid|invalid|missing|total|"
    r"shipped|returned|unique|distinct|active)\s+){0,2}(?:orders?|shipments?|records?|couriers?|labels?|groups?|rows?|parcels?)\b"
    # "(0 missing, 0 invalid)": a status word alone, ending the phrase, is still a count.
    r"|\s*(?:missing|invalid|valid|cancelled|canceled|delivered|undelivered|pending)\b\s*(?=[,;:).]|$|and\b|or\b)", re.I)
# Money words directly governing the number ("charges were 5563.09", "average charge per order of 86.92").
_MONEY_BEFORE = re.compile(
    r"\b(?:charges?|costs?|spend|spent|revenue|amount|loss(?:es)?|invoice|fees?|freight|financial|values?)\b"
    r"(?:\s+(?:per\s+order|in\s+charges|in\s+total))?"
    r"\s*(?:[:=(]|\bof\b|\bwas\b|\bwere\b|\bis\b|\bare\b|\bat\b|\btotall?(?:ing|ed)\b|\bcame\s+to\b)?\s*(?:\u20b9|rs\.?|inr)?\s*$",
    re.I)
_MONEY_AFTER = re.compile(r"\s*(?:inr\b|rupees\b|rs\b|in\s+(?:shipping\s+)?charges\b)", re.I)
_FILLER = {"of", "to", "the", "a", "an", "up", "than", "more", "less", "out"}


def _stem(word):
    word = word.lower()
    return word[:-1] if len(word) > 3 and word.endswith("s") else word


def _note_evidence(metrics):
    """Numbers inside backend-authored data_quality_notes, bound to the word that follows them.

    The notes are generated by deterministic backend code (not the model), and the prompt asks the
    model to mention them. A note number only verifies a claim that repeats it with the same unit
    word (e.g. "15 labels"), so it can never stand in for an observed shipment metric.
    """
    evidence = []
    for i, note in enumerate(metrics.get("data_quality_notes") or []):
        if not isinstance(note, str):
            continue
        for match in _NUMBER.finditer(note):
            words = [w for w in _WORD.findall(note[match.end():match.end() + 40]) if w.lower() not in _FILLER][:3]
            if words:
                evidence.append({"metric": f"data_quality_notes[{i}]", "value": match.group().replace(",", ""),
                                 "kind": "backend_note", "unit": _stem(words[0]), "source": "backend_note"})
    return evidence


def numbers_in_text(*texts):
    # Retained for import compatibility; never grants observed-metric evidence.
    return {Decimal(m.group().replace(",", "")) for text in texts for m in _NUMBER.finditer(text)}


def derived_percentages(metrics):
    """Only named, scope-consistent ratios; never all combinations of numbers."""
    result = []
    total = metrics.get("total_orders")

    def add(name, numerator, denominator):
        if (isinstance(numerator, (int, float)) and not isinstance(numerator, bool)
                and isinstance(denominator, (int, float)) and not isinstance(denominator, bool)
                and denominator > 0 and 0 <= numerator <= denominator):
            result.append({"metric": name, "numerator": numerator, "denominator": denominator,
                           "value": float(Decimal(str(numerator)) * 100 / Decimal(str(denominator)))})

    for group in ("status_category_breakdown", "payment_mode_breakdown"):
        for i, item in enumerate(metrics.get(group, [])):
            add(f"{group}[{i}].percent", item.get("count"), total)
    scoped_status = metrics.get("scope", {}).get("status_filter")
    for i, item in enumerate(metrics.get("courier_performance", [])):
        for category in ("delivered", "in_transit", "pending", "cancelled", "rto", "exception", "lost"):
            if scoped_status and category == scoped_status:
                continue
            add(f"courier_performance[{i}].{category}_percent", item.get(category), item.get("total_orders"))
    for field, coverage in metrics.get("field_coverage", {}).items():
        add(f"field_coverage.{field}.percent", coverage.get("present"), total)
    reasons = metrics.get("cancellation_reasons", {})
    for i, item in enumerate(reasons.get("top_reasons", [])):
        add(f"cancellation_reasons.top_reasons[{i}].percent", item.get("count"), reasons.get("cancelled_orders_with_reason"))
    return result


def _leaves(value, path=""):
    if isinstance(value, dict):
        for key, item in value.items():
            if key not in _STRUCTURE_FIELDS:
                yield from _leaves(item, f"{path}.{key}" if path else key)
    elif isinstance(value, list):
        for i, item in enumerate(value):
            yield from _leaves(item, f"{path}[{i}]")
    else:
        yield path, value


def _registry(metrics):
    evidence = []
    dates = set()
    for path, value in _leaves(metrics):
        if path.startswith(("scope.", "derived_percentages", "data_quality_notes")):
            continue
        if isinstance(value, str) and _DATE.fullmatch(value):
            dates.add(value)
        if path.startswith("shipping_financial.") and isinstance(value, str) and re.fullmatch(r"\d+\.\d{2}", value):
            value = Decimal(value)
        if isinstance(value, bool) or not isinstance(value, (int, float, Decimal)):
            continue
        number = Decimal(str(value))
        if not number.is_finite():
            continue
        kind = "percentage" if any(k in path.lower() for k in ("percent", "rate")) else (
            "count" if path.endswith(".present") or "orders_with" in path else
            "amount" if "order_value" in path or (path.startswith("shipping_financial.") and ("shipping_charges" in path or "average_charge" in path or "charges_associated_with_cancelled_orders" in path)) else "weight" if "weight" in path else "count")
        tags = path
        status_index = re.match(r"status_category_breakdown\[(\d+)\]", path)
        if status_index:
            tags += " " + metrics["status_category_breakdown"][int(status_index[1])].get("category", "")
        if path == "total_orders" and metrics.get("scope", {}).get("status_filter"):
            tags += " " + str(metrics["scope"]["status_filter"])
        evidence.append({"tags": tags, "metric": path, "value": str(number), "kind": kind, "source": "actual_metric"})
    evidence.extend(_note_evidence(metrics))
    for item in derived_percentages(metrics):
        evidence.append({"metric": item["metric"], "value": str(item["value"]), "kind": "percentage",
                         "source": "derived_metric", "numerator": item["numerator"], "denominator": item["denominator"]})
    return evidence, dates


def _data_labels(metrics):
    """Patterns for names in the data that contain digits ("Ekart 0.5 KG", "Delhivery Air 2KG").

    Such a name is an identifier, not a claim: its digits are masked before numbers are checked.
    Only short label strings with a real word qualify; notes, dates and plain numbers never do.
    """
    labels = set()
    for path, value in _leaves(metrics):
        if (isinstance(value, str) and not path.startswith("data_quality_notes") and len(value) <= 80
                and re.search(r"\d", value) and re.search(r"[A-Za-z]{3}", value) and not _DATE.search(value)):
            labels.add(value.strip())
    # Longest first, so "Delhivery 0.5KG DropShip" is masked before "Delhivery 0.5KG".
    return [re.compile(r"(?<![\w.])" + r"\s*".join(re.escape(part) for part in re.findall(r"[A-Za-z]+|\d+(?:\.\d+)?|[^\sA-Za-z\d]", label))
                       + r"(?![\w])", re.I)
            for label in sorted(labels, key=len, reverse=True)]


def validate_numerical_claims(narrative: dict[str, Any], metrics: dict[str, Any], tables: list[dict[str, Any]],
                              extra_allowed=frozenset(), *, user_prompt=""):
    # Table cells are already supplied by Python. Table lengths, prompt numbers,
    # and arbitrary numeric strings must not become evidence for observed facts.
    evidence, dates = _registry(metrics)
    labels = _data_labels(metrics)
    rejected = []
    for path, value in _leaves(narrative):
        if not isinstance(value, str):
            continue
        text = _LIST_MARKER.sub(lambda m: "".join("\n" if c == "\n" else " " for c in m.group()), value)
        for match in _DATE_CLAIM.finditer(text):
            if _normalized_date(match) not in dates:
                rejected.append({"value": match.group(), "field": path, "section": path.split(".")[0],
                                 "span": {"start": match.start(), "end": match.end()},
                                 "semantic_type": "date", "reason": "Date is not a verified dataset boundary", "verified_metrics": sorted(dates)})
        # Mask the complete date without shifting rejection/repair offsets. Its
        # day and year must never be compared with shipment counts or amounts.
        text = _DATE_CLAIM.sub(lambda m: " " * len(m.group()), text)
        original = text  # unmasked, for readable diagnostics; offsets are identical
        for label in labels:
            text = label.sub(lambda m: re.sub(r"\S", "x", m.group()), text)
        identifiers = [m.span(1) for m in _IDENTIFIER.finditer(text)]
        for match in _NUMBER.finditer(text):
            if any(a <= match.start() < b for a, b in identifiers):
                continue
            number = Decimal(match.group().replace(",", ""))
            # Separate neighboring claims at sentence boundaries, but keep decimal points.
            boundaries = list(re.finditer(r"(?<!\d)[.!?;]\s+", text))
            left = max((b.end() for b in boundaries if b.end() <= match.start()), default=0)
            right = min((b.start() for b in boundaries if b.start() >= match.end()), default=len(text))
            sentence = text[left:right]
            after = text[match.end():match.end()+20]
            before = text[max(0, match.start()-35):match.start()]
            money_local = bool(_MONEY_BEFORE.search(before)) or bool(_MONEY_AFTER.match(after))
            # Percent may be stated after the number ("23.4%") or before it ("percent of 23.4",
            # "cancellation rate: 23.4"). A nearby monetary unit takes precedence
            # over an inferred percentage ("share of charges at 280357.60").
            # An explicit %/percent suffix still takes precedence over money words.
            percent_before = re.search(r"\b(?:percent(?:age)?|rate|share)\b(?:\s+(?:of\s+)?[a-z]+){0,3}?\s*(?:of|is|was|=|:|at|stands\s+at)?\s*$", before, re.I) \
                and not money_local and not _COUNT_AFTER.match(after) and not _COUNT_NOUN.match(after)
            kind = "percentage" if re.match(r"\s*(%|percent\b)", after, re.I) or percent_before else (
                "amount" if re.search(r"(?:\u20b9|\$|\bINR|\bRs\.?|\blosses|\brevenue|\bfinancial)\s*$", before, re.I) else
                "weight" if re.match(r"\s*(kg|kilogram)\b", after, re.I) else "count")
            if len(match.group()) == 4 and 1900 <= number <= 2100 and any(d.startswith(match.group() + "-") for d in dates):
                continue
            # An action may cite an observed count. Its field location does not
            # turn that count into a target. Check the local clause preceding
            # this specific number, rather than unrelated words in the sentence.
            clause_start = max(sentence.rfind(",", 0, max(0, match.start()-left)),
                               sentence.rfind(";", 0, max(0, match.start()-left))) + 1
            claim_prefix = sentence[clause_start:max(0, match.start()-left)]
            is_target = bool(_TARGET.search(claim_prefix)) or bool(
                re.search(r"\b(?:within|next)\s*(?:the\s+next\s*)?$", claim_prefix, re.I)
                and re.match(r"\s*(?:days?|weeks?|months?|hours?|years?)\b", after, re.I)
            ) or bool(re.match(r"\s*%?\s*(?:target|goal)\b", after, re.I))
            # Explicit ranking requests are formatting, not observed counts.
            ranking = re.search(r"\btop\s*$", before, re.I)
            if ranking and re.search(rf"\btop\s+{re.escape(match.group())}\b", user_prompt, re.I):
                continue
            # Classify by the words *next to* this number, not by money words anywhere in the
            # sentence: financial reports mention charges in almost every sentence, which used to
            # turn every order count into an "amount". A counted noun makes it a count; money
            # words governing it make it an amount; with neither, it must equal a verified count
            # or amount. It is never accepted without matching a verified metric.
            # A count noun *before* the number ("64 orders: 5563.09") only labels whole numbers;
            # a counted noun *after* it ("86.92 orders") still forces a count, so it is rejected.
            integral = number == number.to_integral_value()
            explicit_count = bool(_COUNT_NOUN.match(after)) or bool(_COUNT_AFTER.match(after)) or integral and bool(re.search(
                r"\b(?:orders?(?:\s+with\s+(?:valid|missing|invalid)\s+charges?)?|records?|couriers?|missing|invalid)\s*[:=(]?\s*$",
                before, re.I,
            ))
            if re.search(r"\bcharges\s+(?:on|associated\s+with)\s+(?:cancelled\s+)?orders\s*:\s*$", before, re.I):
                explicit_count = False
            # Financial comparison wording supplies units, not numerical proof.
            # The resulting value must still equal a verified monetary metric.
            financial_comparison = "shipping_financial" in metrics and bool(re.search(
                r"\b(?:COD|Prepaid|ToPay)\b", sentence, re.I,
            )) and bool(re.search(r"\b(?:totals?|average|per order|versus)\b", sentence, re.I))
            if kind == "count" and not explicit_count:
                if money_local or financial_comparison or number != number.to_integral_value():
                    kind = "amount"
                elif re.search(r"\b(?:loss|losses|revenue|invoice|financial|cost|amount|charges?|shipping|(?:order|invoice|declared|cod)\s+values?)\b", sentence, re.I):
                    kind = "count_or_amount"
            # A count can never exceed the largest verified count (e.g. 64 orders). A larger number
            # labelled only by a preceding word ("COD orders: 2345678") is a money figure; it must
            # still equal a verified amount. A counted noun *after* it ("2345678 orders") stays a
            # count and is rejected.
            explicit_count_label = re.search(r"\b(?:orders?|shipments?)\s+with\s+(?:valid|missing|invalid)\b[^.;:]*[:=(]?\s*$|\b(?:missing|invalid|valid)\s*[:=(]\s*$", before, re.I)
            if kind == "count" and not _COUNT_AFTER.match(after) and not _COUNT_NOUN.match(after) and not explicit_count_label:
                max_count = max((Decimal(e["value"]) for e in evidence if e["kind"] == "count"), default=None)
                if max_count is not None and number > max_count:
                    kind = "amount"
            candidates = [e for e in evidence if e["kind"] == kind or (kind == "count_or_amount" and e["kind"] in ("count", "amount"))]
            named = re.search(r"\b(delivery|delivered|cancellation|cancelled|rto)(?:\s+rate)?\s*[:=(]?\s*$", before, re.I)
            if kind == "count" and not named:
                named = re.match(r"\s*(delivered|cancelled|rto)\b", after, re.I)
            if named:
                category = {"delivery": "delivered", "cancellation": "cancelled"}.get(named[1].lower(), named[1].lower())
                matching = [e for e in candidates if category in e.get("tags", e["metric"])]
                if matching:
                    candidates = matching
            def supported(e):
                exact = Decimal(e["value"])
                if kind != "percentage":
                    return number == exact
                # Half of the last stated decimal place, capped at half a percentage point.
                tolerance = min(Decimal("0.5"), Decimal(1).scaleb(number.as_tuple().exponent) / 2)
                return abs(number - exact) <= tolerance
            # Numeric recommendation targets are disabled by server policy even
            # if an identical number happens to occur in observed metrics.
            unit_words = {_stem(w) for w in _WORD.findall(after) if w.lower() not in _FILLER}
            note_supported = any(e["kind"] == "backend_note" and Decimal(e["value"]) == number and e["unit"] in unit_words
                                 for e in evidence)
            historical = bool(re.search(r"\b(last year|previous year|prior period|year.over.year|month.over.month|historically)\b", sentence, re.I))
            if is_target or historical or not (note_supported or any(supported(e) for e in candidates)):
                rejected.append({"value": str(number), "field": path, "section": path.split(".")[0],
                                 "span": {"start": match.start(), "end": match.end()},
                                 "context": original[left:right].strip()[:200],
                                 "semantic_type": "proposed_recommendation" if is_target else ("derived_metric" if kind == "percentage" else "actual_metric"),
                                 "reason": "Numerical targets are disabled by report policy" if is_target else "Historical comparison is not available in verified data" if historical else f"No verified {kind.replace('_', ' ')} matches at the stated precision",
                                 "verified_metrics": candidates})
    if rejected:
        error = AIResponseError("The AI report contains unsupported numerical claims.", code="ai_unverified_numbers",
                                details={"unsupported_value_count": len(rejected), "fields": list(dict.fromkeys(r["field"] for r in rejected))[:20]})
        error.rejections = rejected
        error.unsupported_values = sorted({r["value"] for r in rejected})[:10]
        raise error


_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")
_LONG_DIGITS = re.compile(r"(?<![\d-])\d[\d\s-]{5,}\d(?![\d-])")
_MAX_CANDIDATES = 8


def safe_rejections(rejections):
    """Numeric diagnostics for logs and correction prompts.

    Long digit strings and e-mail addresses are redacted (possible PII), the claim context is
    truncated, and only the verified metrics closest to the rejected value are kept.
    """
    result = []
    for rejection in rejections:
        item = dict(rejection)
        digits = re.sub(r"\D", "", item["value"])
        if item.get("semantic_type") != "date" and len(digits) >= 7 and "-" not in item["value"]:
            item["value"] = "[redacted long numeric value]"
        if "context" in item:
            item["context"] = _LONG_DIGITS.sub("[redacted]", _EMAIL.sub("[redacted]", item["context"]))[:200]
        candidates = item.get("verified_metrics") or []
        if candidates and isinstance(candidates[0], dict):
            try:
                target = Decimal(rejection["value"])
                candidates = sorted(candidates, key=lambda e: abs(Decimal(e["value"]) - target))
            except Exception:
                pass
            item["verified_metric_count"] = len(candidates)
            item["verified_metrics"] = candidates[:_MAX_CANDIDATES]
        result.append(item)
    return result


_NARRATIVE_PATH = re.compile(
    r"^(?:executive_summary(?:\.(?:paragraphs|highlights)\[\d+\])?|"
    r"sections\[\d+\]\.(?:content|blocks\[\d+\]\.(?:text|items\[\d+\]))|"
    r"findings\[\d+\]\.detail|recommendations\[\d+\]\.(?:action|rationale)|"
    r"data_limitations\[\d+\])$"
)


class NarrativeRepairError(ValueError):
    """A rejected field cannot be changed without risking valid content."""


_TITLE_OWNER = re.compile(r"^((?:findings|sections)\[\d+\])\.title$")
_DEPENDENT = re.compile(r"(?:this|these|that|those|it|therefore|consequently|thus|as a result)\b", re.I)


def _owner_of_empty(path):
    """The list item to drop when the text at `path` has no sentence left."""
    if re.fullmatch(r"(?:executive_summary\.(?:paragraphs|highlights)|data_limitations)\[\d+\]"
                    r"|sections\[\d+\]\.blocks\[\d+\]\.items\[\d+\]", path):
        return path
    owner = re.fullmatch(r"(sections\[\d+\]\.blocks\[\d+\])\.text|(sections\[\d+\])\.content"
                         r"|(findings\[\d+\])\.detail|(recommendations\[\d+\])\.action", path)
    return next(g for g in owner.groups() if g) if owner else None


def _locate(root, path):
    tokens = re.findall(r"[a-z_]+|\d+", path)
    parent = root
    for token in tokens[:-1]:
        parent = parent[int(token)] if isinstance(parent, list) else parent[token]
    key = int(tokens[-1]) if isinstance(parent, list) else tokens[-1]
    parent[key]  # raises when the path does not exist
    return parent, key


def repair_unsupported_narrative(narrative, rejections):
    """Remove the sentences that hold unsupported numbers, using exact original offsets.

    Operates on a copy and never rewrites or invents a number: removing a sentence can only
    drop information, not add a wrong figure. A following sentence that depends on a removed
    one ("This shows ...") goes with it. A text field left with no sentence drops its list item
    (paragraph, bullet, block, finding, recommendation); an empty rationale becomes "". An
    unsupported number in a finding or section title drops that finding or section.
    The caller MUST validate the resulting schema and evidence again.
    """
    from copy import deepcopy
    repaired = deepcopy(narrative)
    grouped = {}
    drop = set()
    for rejection in rejections:
        path = rejection.get("field", "")
        title = _TITLE_OWNER.fullmatch(path)
        if title:
            drop.add(title[1])
            continue
        if not _NARRATIVE_PATH.fullmatch(path):
            raise NarrativeRepairError("Unsupported claim is outside a repairable narrative field")
        grouped.setdefault(path, []).append(rejection)
    if not grouped and not drop:
        raise NarrativeRepairError("No exact claims supplied for repair")

    for path, claims in grouped.items():
        try:
            parent, key = _locate(repaired, path)
        except (KeyError, IndexError, TypeError, ValueError) as exc:
            raise NarrativeRepairError("Rejection path does not identify an existing text field") from exc
        text = parent[key]
        if not isinstance(text, str):
            raise NarrativeRepairError("Repair target is not text")
        spans = []
        for claim in claims:
            span = claim.get("span", {})
            start, end = span.get("start"), span.get("end")
            if not isinstance(start, int) or not isinstance(end, int) or not 0 <= start < end <= len(text):
                raise NarrativeRepairError("Missing or invalid original claim offsets")
            fragment = text[start:end]
            try:
                matches = fragment == claim["value"] if claim.get("semantic_type") == "date" else Decimal(fragment.replace(",", "")) == Decimal(claim["value"])
            except Exception:
                matches = False
            if not matches:
                raise NarrativeRepairError("Rejection offsets no longer match the original claim")
            spans.append((start, end))

        # Sentence segmentation preserves decimal numbers, dates, identifiers,
        # list markers, and common abbreviations.
        boundaries = [0]
        for match in re.finditer(r"[.!?](?=\s|$)", text):
            prefix = text[:match.start()]
            if match.group() == "." and re.search(r"(?:\b(?:Rs|Mr|Mrs|Dr|etc|e\.g|i\.e)|\b[A-Za-z])$", prefix, re.I):
                continue
            if match.group() == "." and re.search(r"(?:^|\n)\s*\d+$", prefix):
                continue
            boundaries.append(match.end())
        if boundaries[-1] != len(text):
            boundaries.append(len(text))
        sentences = list(zip(boundaries, boundaries[1:]))
        removed = set()
        for start, end in spans:
            containers = [i for i, (a, b) in enumerate(sentences) if a <= start and end <= b]
            if len(containers) != 1:
                raise NarrativeRepairError("Unsupported claim crosses an ambiguous sentence boundary")
            index = containers[0]
            removed.add(index)
            while index + 1 < len(sentences) and _DEPENDENT.match(text[slice(*sentences[index + 1])].lstrip()):
                index += 1
                removed.add(index)
        text = "".join(text[a:b] for i, (a, b) in enumerate(sentences) if i not in removed)
        text = re.sub(r"[ \t]{2,}", " ", text).strip()
        if text:
            parent[key] = text
        elif path.endswith(".rationale"):
            parent[key] = ""
        else:
            owner = _owner_of_empty(path)
            if owner is None:
                raise NarrativeRepairError("Repair would empty a narrative field")
            drop.add(owner)

    # Deepest and highest indices first, so earlier indices stay valid.
    for path in sorted(drop, key=lambda p: [int(n) for n in re.findall(r"\d+", p)], reverse=True):
        try:
            parent, key = _locate(repaired, path)
        except (KeyError, IndexError, TypeError, ValueError):
            continue
        del parent[key]
    if isinstance(repaired.get("sections"), list):
        for section in repaired["sections"]:
            if isinstance(section, dict) and isinstance(section.get("blocks"), list):
                section["blocks"] = [b for b in section["blocks"]
                                     if not (isinstance(b, dict) and b.get("type") == "bullet_list" and not b.get("items"))]
        repaired["sections"] = [s for s in repaired["sections"]
                                if not (isinstance(s, dict) and "blocks" in s and not s["blocks"])]
    summary = repaired.get("executive_summary")
    if summary == "" or isinstance(summary, dict) and not summary.get("paragraphs"):
        raise NarrativeRepairError("Repair would empty the executive summary")
    return repaired
